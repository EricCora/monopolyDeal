#!/usr/bin/env node
// Bundles the turn-by-turn room function. The output is committed, because Vercel builds
// functions from what's in the repo. `--check` fails if it's out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const OUTPUT = 'api/turn-rooms.js';
const result = await build({
  entryPoints: ['api/turn-rooms.source.ts'],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['@vercel/blob', 'web-push'],
  banner: { js: '// Generated by scripts/build_turn_api.mjs from api/turn-rooms.source.ts. Do not edit.' },
  logLevel: 'silent',
});
const text = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  if (readFileSync(OUTPUT, 'utf8') !== text) {
    console.error(`${OUTPUT} is out of date. Run npm run build:turn-api.`);
    process.exit(1);
  }
  process.exit(0);
}
writeFileSync(OUTPUT, text);
console.log(`${OUTPUT}: ${Math.round(text.length / 1024)} KB`);
