#!/usr/bin/env node
// Bundles the Vercel Functions (turn rooms and problem reports). The output is committed, because Vercel builds
// functions from what's in the repo. `--check` fails if it's out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const BUNDLES = [
  { entry: 'api/turn-rooms.source.ts', output: 'api/turn-rooms.js' },
  { entry: 'api/feedback.source.ts', output: 'api/feedback.js' },
];
let stale = false;
for (const { entry, output } of BUNDLES) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['@vercel/blob', 'web-push'],
    banner: { js: `// Generated by scripts/build_turn_api.mjs from ${entry}. Do not edit.` },
    logLevel: 'silent',
  });
  const text = result.outputFiles[0].text;
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(output, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== text) {
      console.error(`${output} is out of date. Run npm run build:turn-api.`);
      stale = true;
    }
    continue;
  }
  writeFileSync(output, text);
  console.log(`${output}: ${Math.round(text.length / 1024)} KB`);
}
if (stale) process.exit(1);
